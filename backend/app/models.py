"""Database schema.

Three layers:
- Reference: `instrument_metadata` holds each stock's identifiers (ticker, FIGI) and details (name,
  industry, ...). Rows are insert-only, each stamped with `data_version`: the latest row per
  `instrument_id` is current, and the latest row at or before time T is "as was" at T.
  The rows themselves are the audit trail: comparing consecutive rows shows what changed.
- Market data: split-adjusted daily bars keyed by instrument id, never by ticker; versioned the
  same way (insert-only, latest `data_version` per day is current).
- Workspace: baskets (named groups of stocks, optionally with quantities) and annotations.

`instrument_id` is a UUID generated by the app. There is no table of instruments, so other tables
store the UUID without a foreign key; the API checks it exists before writing.
"""

import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    UUID,
    BigInteger,
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

JOB_STATUSES = ("RUNNING", "SUCCEEDED", "FAILED")


def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


class Base(DeclarativeBase):
    pass


# --- Reference layer -------------------------------------------------------------------------


class InstrumentMetadata(Base):
    """One version of a stock's identifiers and details. A change inserts a new row.

    Migration 0002 adds an exclusion constraint: a FIGI may appear in any number of versions of
    one instrument, but never under two different instrument_ids."""

    __tablename__ = "instrument_metadata"
    __table_args__ = (
        CheckConstraint("listing_status IN ('ACTIVE', 'DELISTED')", name="ck_metadata_status"),
        CheckConstraint(
            "shares_outstanding IS NULL OR shares_outstanding > 0", name="ck_metadata_shares"
        ),
        Index("ix_metadata_ticker", "ticker"),
        Index("ix_metadata_figi", "figi"),
    )

    instrument_id: Mapped[uuid.UUID] = mapped_column(UUID, primary_key=True)
    ticker: Mapped[str | None] = mapped_column(Text)  # NULL: ticker taken over by another stock
    figi: Mapped[str | None] = mapped_column(Text)
    name: Mapped[str] = mapped_column(Text)
    sic_code: Mapped[str | None] = mapped_column(Text)
    sic_description: Mapped[str | None] = mapped_column(Text)
    primary_exchange: Mapped[str | None] = mapped_column(Text)
    currency: Mapped[str] = mapped_column(String(3))
    shares_outstanding: Mapped[int | None] = mapped_column(BigInteger)
    listing_status: Mapped[str] = mapped_column(String(16))
    description: Mapped[str | None] = mapped_column(Text)
    homepage_url: Mapped[str | None] = mapped_column(Text)
    total_employees: Mapped[int | None] = mapped_column(Integer)
    list_date: Mapped[date | None] = mapped_column(Date)
    hq_city: Mapped[str | None] = mapped_column(Text)
    hq_state: Mapped[str | None] = mapped_column(Text)
    data_version: Mapped[datetime] = mapped_column(DateTime(timezone=True), primary_key=True)


# --- Market data layer -----------------------------------------------------------------------


class InstrumentDailyPrice(Base):
    """One version of a stock's split-adjusted daily bar from Polygon. Insert-only: when Polygon's
    bar for a day changes (e.g. history rescaled by a split), a new version is added and the old
    one is kept. The latest `data_version` per (instrument_id, trade_date) is current."""

    __tablename__ = "instrument_daily_price"
    __table_args__ = (
        CheckConstraint(
            "open > 0 AND high > 0 AND low > 0 AND close > 0", name="ck_price_positive"
        ),
        CheckConstraint("high >= low", name="ck_price_high_low"),
        CheckConstraint("volume >= 0", name="ck_price_volume"),
    )

    instrument_id: Mapped[uuid.UUID] = mapped_column(UUID, primary_key=True)
    trade_date: Mapped[date] = mapped_column(Date, primary_key=True)
    data_version: Mapped[datetime] = mapped_column(DateTime(timezone=True), primary_key=True)
    open: Mapped[Decimal] = mapped_column(Numeric(18, 6))
    high: Mapped[Decimal] = mapped_column(Numeric(18, 6))
    low: Mapped[Decimal] = mapped_column(Numeric(18, 6))
    close: Mapped[Decimal] = mapped_column(Numeric(18, 6))
    volume: Mapped[int] = mapped_column(BigInteger)


# --- Workspace layer -------------------------------------------------------------------------


class Basket(Base):
    """A named group of stocks: a theme, a watchlist, or (when every member has a target
    quantity) a mock portfolio."""

    __tablename__ = "basket"
    __table_args__ = (Index("uq_basket_owner_name", "created_by", "name", unique=True),)

    id: Mapped[uuid.UUID] = mapped_column(UUID, primary_key=True, default=uuid.uuid4)
    name: Mapped[str] = mapped_column(Text)
    created_by: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class BasketMember(Base):
    __tablename__ = "basket_member"
    __table_args__ = (
        CheckConstraint(
            "target_quantity IS NULL OR target_quantity <> 0", name="ck_member_quantity"
        ),
    )

    basket_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("basket.id", ondelete="CASCADE"), primary_key=True
    )
    instrument_id: Mapped[uuid.UUID] = mapped_column(UUID, primary_key=True)
    target_quantity: Mapped[Decimal | None] = mapped_column(Numeric(18, 4))
    added_by: Mapped[str] = mapped_column(Text)
    added_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class Annotation(Base):
    __tablename__ = "annotation"
    __table_args__ = (
        CheckConstraint("length(body) > 0", name="ck_annotation_body"),
        Index("ix_annotation_instrument_time", "instrument_id", "created_at"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID, primary_key=True, default=uuid.uuid4)
    instrument_id: Mapped[uuid.UUID] = mapped_column(UUID)
    author: Mapped[str] = mapped_column(Text)
    body: Mapped[str] = mapped_column(Text)
    # Optional: the day the annotation is about (e.g. an earnings date).
    annotation_date: Mapped[date | None] = mapped_column(Date)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    # Set when the author edits the annotation; NULL for an annotation that was never changed.
    edited_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


# --- Operations ------------------------------------------------------------------------------


class JobRun(Base):
    __tablename__ = "job_run"
    __table_args__ = (CheckConstraint(_in("status", JOB_STATUSES), name="ck_job_status"),)

    id: Mapped[uuid.UUID] = mapped_column(UUID, primary_key=True, default=uuid.uuid4)
    job: Mapped[str] = mapped_column(String(32))
    params: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    status: Mapped[str] = mapped_column(String(16))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    rows_written: Mapped[int | None] = mapped_column(Integer)
    error: Mapped[str | None] = mapped_column(Text)
