# --- 1. Reference data -------------------------------------------------------------------------

INSTRUMENT_METADATA = """
-- One version of a stock's identifiers and details. A change inserts a new row; the latest row
-- per instrument_id is current. A ticker change (FB -> META) is just a new row with the same
-- instrument_id, so prices, baskets and notes keyed by instrument_id are unaffected.
CREATE TABLE instrument_metadata (
    instrument_id       UUID        NOT NULL,
    ticker              TEXT,                   -- NULL: ticker taken over by another stock
    figi                TEXT,                   -- composite FIGI
    name                TEXT        NOT NULL,
    sic_code            TEXT,
    sic_description     TEXT,
    primary_exchange    TEXT,
    currency            VARCHAR(3)  NOT NULL,
    shares_outstanding  BIGINT,
    listing_status      VARCHAR(16) NOT NULL,
    data_version        TIMESTAMPTZ NOT NULL,

    CONSTRAINT ck_metadata_status
        CHECK (listing_status IN ('ACTIVE', 'DELISTED')),
    CONSTRAINT ck_metadata_shares
        CHECK (shares_outstanding IS NULL OR shares_outstanding > 0),
    PRIMARY KEY (instrument_id, data_version)
)
"""

INSTRUMENT_METADATA_INDEXES = [
    "CREATE INDEX ix_metadata_ticker ON instrument_metadata (ticker)",
    "CREATE INDEX ix_metadata_figi ON instrument_metadata (figi)",
]


# --- 2. Market data ----------------------------------------------------------------------------

INSTRUMENT_DAILY_PRICE = """
-- Split-adjusted daily bars from Polygon, versioned like instrument_metadata: insert-only, and a
-- new version is added only when Polygon's bar for that day changes (e.g. history rescaled by a
-- split). The latest data_version per (instrument_id, trade_date) is current.
CREATE TABLE instrument_daily_price (
    instrument_id  UUID          NOT NULL,
    trade_date     DATE          NOT NULL,
    data_version   TIMESTAMPTZ   NOT NULL,
    open           NUMERIC(18,6) NOT NULL,
    high           NUMERIC(18,6) NOT NULL,
    low            NUMERIC(18,6) NOT NULL,
    close          NUMERIC(18,6) NOT NULL,
    volume         BIGINT        NOT NULL,

    PRIMARY KEY (instrument_id, trade_date, data_version),
    CONSTRAINT ck_price_positive  CHECK (open > 0 AND high > 0 AND low > 0 AND close > 0),
    CONSTRAINT ck_price_high_low  CHECK (high >= low),
    CONSTRAINT ck_price_volume    CHECK (volume >= 0)
)
"""


