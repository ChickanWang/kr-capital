JOB_RUN = """
-- One row per ETL run, so failures and history are visible without an orchestrator.
CREATE TABLE job_run (
    id            UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    job           VARCHAR(32) NOT NULL,   -- load, prices, topup, reference, restore-seed
    params        JSONB,
    status        VARCHAR(16) NOT NULL,
    started_at    TIMESTAMPTZ NOT NULL,
    finished_at   TIMESTAMPTZ,
    rows_written  INTEGER,
    error         TEXT,

    CONSTRAINT ck_job_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED'))
)
"""

INSTRUMENT_SNAPSHOT = """
-- Grid rows: current ticker and name, last close, 1-day / 1-month / year-to-date price returns,
-- and market cap. A regular view, so it is computed on every read and is never stale. Every price
-- lookup orders by trade_date and then data_version, so it reads the latest version of that
-- day's bar.
CREATE VIEW instrument_snapshot AS
WITH current_metadata AS (
    SELECT DISTINCT ON (instrument_id) *
    FROM instrument_metadata
    ORDER BY instrument_id, data_version DESC
),
last_bar AS (
    SELECT DISTINCT ON (instrument_id) instrument_id, trade_date, close
    FROM instrument_daily_price
    ORDER BY instrument_id, trade_date DESC, data_version DESC
)
SELECT
    m.instrument_id,
    m.ticker,
    m.name,
    m.sic_description,
    lb.trade_date                       AS last_trade_date,
    lb.close                            AS last_close,
    lb.close / prev.close - 1           AS ret_1d,
    lb.close / m1.close - 1             AS ret_1m,
    lb.close / ytd.close - 1            AS ret_ytd,
    lb.close * m.shares_outstanding     AS market_cap
FROM current_metadata m
LEFT JOIN last_bar lb ON lb.instrument_id = m.instrument_id
-- previous trading day's close
LEFT JOIN LATERAL (
    SELECT close FROM instrument_daily_price p
    WHERE p.instrument_id = m.instrument_id AND p.trade_date < lb.trade_date
    ORDER BY p.trade_date DESC, p.data_version DESC LIMIT 1
) prev ON true
-- close one month earlier (or the nearest trading day before)
LEFT JOIN LATERAL (
    SELECT close FROM instrument_daily_price p
    WHERE p.instrument_id = m.instrument_id
      AND p.trade_date <= lb.trade_date - interval '1 month'
    ORDER BY p.trade_date DESC, p.data_version DESC LIMIT 1
) m1 ON true
-- last close of the previous year
LEFT JOIN LATERAL (
    SELECT close FROM instrument_daily_price p
    WHERE p.instrument_id = m.instrument_id
      AND p.trade_date < date_trunc('year', lb.trade_date)
    ORDER BY p.trade_date DESC, p.data_version DESC LIMIT 1
) ytd ON true
WHERE m.ticker IS NOT NULL
"""


